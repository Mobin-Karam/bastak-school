import { mkdir, readFile, readdir, writeFile } from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const adminRoot = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const sourceRoot = path.join(adminRoot, "src");
const outputPath = path.join(sourceRoot, "stories", "component-catalog.generated.ts");
const checkOnly = process.argv.includes("--check");

async function walk(directory) {
  const entries = await readdir(directory, { withFileTypes: true });
  const files = await Promise.all(
    entries.map(async (entry) => {
      const entryPath = path.join(directory, entry.name);
      if (entry.isDirectory()) return walk(entryPath);
      return [entryPath];
    }),
  );
  return files.flat();
}

function exportedComponents(source) {
  const names = new Set();
  const declaration = /export\s+(?:async\s+)?(?:function|class|const)\s+([A-Z][A-Za-z0-9_]*)/g;
  for (const match of source.matchAll(declaration)) names.add(match[1]);
  return [...names].sort();
}

function storyPathFor(relativePath, allPaths) {
  const withoutExtension = relativePath.replace(/\.tsx$/, "");
  const candidate = `${withoutExtension}.stories.tsx`;
  return allPaths.has(candidate) ? candidate : null;
}

function sourceFor(entries) {
  return `// Generated by scripts/generate-storybook-catalog.mjs. Do not edit by hand.\n\nexport type ComponentCatalogEntry = {\n  sourcePath: string;\n  kind: "component" | "page";\n  exports: readonly string[];\n  storyPath: string | null;\n};\n\nexport const componentCatalog = ${JSON.stringify(entries, null, 2)} as const satisfies readonly ComponentCatalogEntry[];\n\nexport const adminStoryRoutes = ${JSON.stringify(routePaths, null, 2)} as const;\n`;
}

const allFiles = await walk(sourceRoot);
const allRelativePaths = new Set(
  allFiles.map((file) => path.relative(sourceRoot, file).split(path.sep).join("/")),
);
const components = [];
const routerSource = await readFile(path.join(sourceRoot, "app", "routing", "router.tsx"), "utf8");
const routePaths = [
  "/admin",
  ...new Set(
    [...routerSource.matchAll(/\bpath:\s*"([^"]+)"/g)]
      .map((match) => match[1])
      .filter((route) => route !== "*" && route !== "/admin")
      .map((route) => (route.startsWith("/") ? route : `/admin/${route}`)),
  ),
].sort();

for (const file of allFiles.sort()) {
  const relativePath = path.relative(sourceRoot, file).split(path.sep).join("/");
  if (
    !relativePath.endsWith(".tsx") ||
    /\.(test|stories)\.tsx$/.test(relativePath) ||
    relativePath.startsWith("features/identity/registration/")
  )
    continue;
  const exports = exportedComponents(await readFile(file, "utf8"));
  if (exports.length === 0) continue;
  components.push({
    sourcePath: relativePath,
    kind: relativePath.includes("/pages/") ? "page" : "component",
    exports,
    storyPath: storyPathFor(relativePath, allRelativePaths),
  });
}

const prettierConfig = (await prettier.resolveConfig(outputPath)) ?? {};
const generated = await prettier.format(sourceFor(components), {
  ...prettierConfig,
  filepath: outputPath,
});
if (checkOnly) {
  const current = await readFile(outputPath, "utf8").catch(() => "");
  if (current !== generated) {
    throw new Error(
      "Storybook component catalog is stale. Run `npm run storybook:catalog` in apps/admin.",
    );
  }
  console.log(`Storybook catalog is current (${components.length} component modules).`);
} else {
  await mkdir(path.dirname(outputPath), { recursive: true });
  await writeFile(outputPath, generated, "utf8");
  console.log(`Generated Storybook catalog for ${components.length} component modules.`);
}
